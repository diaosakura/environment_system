CREATE DATABASE IF NOT EXISTS environment_system CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE environment_system;

CREATE TABLE IF NOT EXISTS admins (
 admin_id BIGINT PRIMARY KEY AUTO_INCREMENT,
 admin_code VARCHAR(32) NOT NULL UNIQUE,
 password_hash VARCHAR(100) NOT NULL,
 real_name VARCHAR(40) NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS supervisor (
 tel_id VARCHAR(11) PRIMARY KEY,
 password_hash VARCHAR(100) NOT NULL,
 real_name VARCHAR(40) NOT NULL,
 birthday DATE NULL,
 sex TINYINT NOT NULL DEFAULT 1,
 enabled BOOLEAN NOT NULL DEFAULT TRUE,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 CONSTRAINT ck_supervisor_sex CHECK (sex IN (0,1))
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS grid_province (
 province_id INT PRIMARY KEY,
 province_name VARCHAR(30) NOT NULL UNIQUE,
 province_abbr VARCHAR(3) NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS grid_city (
 city_id INT PRIMARY KEY,
 city_name VARCHAR(30) NOT NULL,
 province_id INT NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 UNIQUE KEY uk_city_province(city_id,province_id),
 FOREIGN KEY(province_id) REFERENCES grid_province(province_id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS grid_member (
 gm_id BIGINT PRIMARY KEY AUTO_INCREMENT,
 gm_code VARCHAR(32) NOT NULL UNIQUE,
 password_hash VARCHAR(100) NOT NULL,
 gm_name VARCHAR(40) NOT NULL,
 tel VARCHAR(11) NOT NULL,
 province_id INT NOT NULL,
 city_id INT NOT NULL,
 enabled BOOLEAN NOT NULL DEFAULT TRUE,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 FOREIGN KEY(city_id,province_id) REFERENCES grid_city(city_id,province_id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS aqi (
 aqi_id INT PRIMARY KEY,
 chinese_explain VARCHAR(3) NOT NULL,
 aqi_explain VARCHAR(20) NOT NULL,
 color VARCHAR(7) NOT NULL,
 health_impact VARCHAR(400) NOT NULL,
 so2_max DECIMAL(10,3) NULL,
 co_max DECIMAL(10,3) NULL,
 spm_max DECIMAL(10,3) NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS aqi_feedback (
 af_id BIGINT PRIMARY KEY AUTO_INCREMENT,
 tel_id VARCHAR(11) NOT NULL,
 province_id INT NOT NULL,
 city_id INT NOT NULL,
 address VARCHAR(200) NOT NULL,
 information VARCHAR(400) NOT NULL,
 estimated_grade INT NOT NULL,
 gm_id BIGINT NULL,
 state TINYINT NOT NULL DEFAULT 0,
 submitted_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 assigned_at DATETIME NULL,
 confirmed_at DATETIME NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 FOREIGN KEY(tel_id) REFERENCES supervisor(tel_id),
 FOREIGN KEY(city_id,province_id) REFERENCES grid_city(city_id,province_id),
 FOREIGN KEY(estimated_grade) REFERENCES aqi(aqi_id),
 FOREIGN KEY(gm_id) REFERENCES grid_member(gm_id),
 INDEX ix_feedback_owner(tel_id,submitted_at),
 INDEX ix_feedback_grid(gm_id,state),
 INDEX ix_feedback_state(state,submitted_at),
 CONSTRAINT ck_feedback_state CHECK(state IN (0,1,2))
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS statistics (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,
 feedback_id BIGINT NOT NULL UNIQUE,
 so2_value DECIMAL(10,3) NOT NULL,
 co_value DECIMAL(10,3) NOT NULL,
 spm_value DECIMAL(10,3) NOT NULL,
 so2_level INT NOT NULL,
 co_level INT NOT NULL,
 spm_level INT NOT NULL,
 aqi_id INT NOT NULL,
 confirmed_at DATETIME NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 FOREIGN KEY(feedback_id) REFERENCES aqi_feedback(af_id),
 FOREIGN KEY(aqi_id) REFERENCES aqi(aqi_id),
 INDEX ix_statistics_date(confirmed_at),
 CONSTRAINT ck_measurement_values CHECK(so2_value >= 0 AND co_value >= 0 AND spm_value >= 0)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS operation_log (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,
 actor_id VARCHAR(32) NOT NULL,
 actor_name VARCHAR(40) NOT NULL,
 actor_role VARCHAR(20) NOT NULL,
 action VARCHAR(60) NOT NULL,
 target_id VARCHAR(50) NOT NULL,
 result VARCHAR(20) NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 INDEX ix_log_date(created_at)
) ENGINE=InnoDB;
